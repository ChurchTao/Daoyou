function tiers({
  seriesId,
  idPrefix,
  metric,
  entries,
  description,
  condition,
}: {
  seriesId: string;
  idPrefix: string;
  metric: string;
  entries: readonly (readonly [number, string, number])[];
  description: string;
  condition: (target: number) => string;
}): AchievementDefinition[] {
  return entries.map(([target, name, reputationReward], index) => ({
    id: idPrefix + '.' + target,
    seriesId,
    tier: index + 1,
    name,
    reputationReward,
    description,
    condition: condition(target),
    requirement: { metric, target },
  }));
}

