#!/usr/bin/env python3
"""Package the bundled color emoji font.

Source: Noto Color Emoji COLRv1 without regional flags, from
https://github.com/googlefonts/noto-emoji (2D/fonts/Noto-COLRv1-noflags.ttf).
The file is renamed Daoyou Emoji and is not processed by vite-plugin-font.
Keep the whole emoji set so a new interface emoji does not need another build.
Replace this file only when upgrading the upstream Noto emoji font.

    python3 apps/web/scripts/subset-emoji-font.py /path/to/Noto-COLRv1-noflags.ttf
"""

from __future__ import annotations

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT_PATH = ROOT / "src/assets/fonts/DaoyouEmoji.woff2"
CSS_PATH = ROOT / "src/assets/fonts/daoyou-emoji.css"


def rename(font: TTFont) -> None:
    name = font["name"]
    values = {
        0: "Copyright 2022 Google Inc. Noto Color Emoji, flags removed, renamed for Daoyou.",
        1: "Daoyou Emoji",
        2: "Regular",
        3: "Daoyou Emoji",
        4: "Daoyou Emoji",
        6: "DaoyouEmoji",
    }
    for name_id, value in values.items():
        name.setName(value, name_id, 3, 1, 0x409)
        name.setName(value, name_id, 1, 0, 0)


def unicode_range(codepoints: list[int]) -> str:
    ranges: list[str] = []
    start = end = codepoints[0]
    for codepoint in codepoints[1:]:
        if codepoint == end + 1:
            end = codepoint
            continue
        ranges.append(f"U+{start:04X}" if start == end else f"U+{start:04X}-{end:04X}")
        start = end = codepoint
    ranges.append(f"U+{start:04X}" if start == end else f"U+{start:04X}-{end:04X}")
    return ", ".join(ranges)


def write_css(codepoints: list[int]) -> None:
    # U+FE0F has no glyph of its own. Keep it in range so an emoji sequence
    # stays with this face instead of splitting off the variation selector.
    if 0xFE0F not in codepoints:
        codepoints = sorted([*codepoints, 0xFE0F])
    CSS_PATH.write_text(
        "\n".join(
            [
                "/* Generated by apps/web/scripts/subset-emoji-font.py. */",
                "/* Icons use this face. Body text does not. */",
                "@font-face {",
                '  font-family: "Daoyou Emoji";',
                "  font-style: normal;",
                "  font-weight: 400;",
                "  font-display: swap;",
                '  src: url("./DaoyouEmoji.woff2") format("woff2") tech(color-COLRv1);',
                f"  unicode-range: {unicode_range(codepoints)};",
                "}",
                "",
            ]
        ),
        encoding="utf-8",
    )


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: subset-emoji-font.py Noto-COLRv1-noflags.ttf")
    font = TTFont(sys.argv[1])
    rename(font)
    codepoints = sorted((font.getBestCmap() or {}).keys())
    if not codepoints:
        raise SystemExit("source font has no cmap")
    font.flavor = "woff2"
    font.save(FONT_PATH)
    write_css(codepoints)
    print(
        f"wrote {FONT_PATH} ({FONT_PATH.stat().st_size} bytes, {len(codepoints)} cmap)"
    )


if __name__ == "__main__":
    main()
