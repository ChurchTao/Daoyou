import { getSectAtlasData } from '@daoyou/game-rules/sects/atlas';
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';

const repositoryRoot = resolve(import.meta.dirname, '..');
const destination = process.argv.slice(2).find((argument) => argument !== '--');
if (!destination) {
  throw new Error('请指定官网仓库目录：pnpm run website:sects -- /path/to/daoyou-website');
}
const websiteRoot = resolve(destination);
const websitePackage = JSON.parse(await readFile(resolve(websiteRoot, 'package.json'), 'utf8'));
if (websitePackage.name !== 'daoyou-website') {
  throw new Error('目标必须是 daoyou-website 仓库，未写入任何文件。');
}

const hash = (value: string | Uint8Array) => createHash('sha256').update(value).digest('hex');
const catalog = getSectAtlasData();
for (const sect of catalog.sects) {
  for (const status of sect.statuses) {
    if (!status.description.trim()) throw new Error(`状态缺少释义：${status.id}`);
  }
}
const dataHash = hash(JSON.stringify(catalog));
const sourceHashPlaceholder = '__DAOYOU_SECT_ATLAS_SOURCE_HASH__';
const require = createRequire(import.meta.url);
const atlasEntry = require.resolve('@daoyou/game-rules/sects/atlas');
const bundled = await build({
  stdin: {
    contents: `export { previewSectAtlasBuild, toggleSectAtlasNode } from '@daoyou/game-rules/sects/atlas';\nexport const SECT_ATLAS_SOURCE_HASH = ${JSON.stringify(sourceHashPlaceholder)};`,
    resolveDir: repositoryRoot,
    sourcefile: 'website-sect-preview.js',
  },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'inline',
  charset: 'utf8',
  write: false,
  metafile: true,
});
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repositoryRoot, encoding: 'utf8' }).trim();
const inputs = Object.entries(bundled.metafile.inputs)
  .filter(([path]) => path !== 'website-sect-preview.js')
  .map(([path]) => path)
  .sort();
const compiledHashes = await Promise.all(inputs.map(async (path) => [
  path.replaceAll('\\', '/'),
  hash(await readFile(resolve(repositoryRoot, path))),
]));
const compiledInputHash = hash(JSON.stringify(compiledHashes));
// Bind both the public data and its exact rule inputs, including compiler changes.
const contentHash = hash(`${dataHash}:${compiledInputHash}`);
const runtime = bundled.outputFiles[0].text.replace(sourceHashPlaceholder, contentHash);
const runtimeOutput = `// @ts-nocheck\n// Generated from ChurchTao/Daoyou ${commit}. GPL-3.0.\n${runtime.trimEnd()}\n`;
const source = {
  repository: 'ChurchTao/Daoyou',
  commit,
  dirty: Boolean(execFileSync('git', ['status', '--porcelain', '--', 'packages'], { cwd: repositoryRoot, encoding: 'utf8' }).trim()),
  contentHash,
  dataHash,
  runtimeHash: hash(runtimeOutput),
  compiledInputHash,
};

// Keep the website build independent of workspace packages and local paths.
// Keep the declaration surface small; inferring unions from every raw skill
// definition makes the standalone website type checker expand huge unions.
const declarations = `// Generated by Daoyou/scripts/export-website-sects.ts. Do not edit.
export type SectAtlasNumericField = {
  path: string; label: string; contextLabel: string; value: number | string; display: string;
  resolved: number | null; resolvedDisplay: string | null;
  variables: {name: string; label: string}[];
};
export type SectAtlasSource = {
  type: string; label: string; pathId?: string; nodeId?: string;
};
export type SectAtlasSkill = {
  id: string; name: string; kind: 'active' | 'passive' | 'internal';
  sourceMethodId: string; unlockMethodLevel: number; description: string;
  definition: Record<string, unknown>;
  sources: SectAtlasSource[]; numericFields: SectAtlasNumericField[];
};
export type SectAtlasPath = {
  id: string; name: string; description: string; requiresConnectedNodes?: boolean;
  nodes: {id: string; name: string; description: string; layer: number; slot: number; automatic?: boolean}[];
};
export type SectAtlasStatus = {
  id: string; name: string; description: string; definition: Record<string, unknown>;
  numericFields: SectAtlasNumericField[]; referencedBySkillIds: string[];
};
export type SectAtlasSect = {
  id: string; name: string;
  methods: {id: string; name: string; slot: number; isPrimary: boolean; description?: string}[];
  paths: SectAtlasPath[]; skills: SectAtlasSkill[]; statuses: SectAtlasStatus[];
  resources: {id: string; name: string; current: number; min?: number; max: number}[];
};
export type SectAtlasData = {
  formatVersion: number;
  limits: {maxCharacterLevel: number; maxMethodLevel: number; meridianCharacterLevels: number[]};
  sects: SectAtlasSect[];
};
export type SectAtlasBuildInput = {
  sectId: string;
  pathId: string;
  characterLevel: number;
  methods?: Record<string, number>;
  nodeIds?: string[];
};
export type SectAtlasBuildPreview = {
  ok: boolean;
  characterLevel: number;
  progress: {
    version: number;
    sectId: string;
    activePathId: string;
    methods: Record<string, number>;
    meridianDepth: number;
    meridianLoadouts: {pathId: string; nodeIds: string[]; revision: number}[];
  };
  selectedNodeIds: string[];
  automaticNodeIds: string[];
  diagnostics: {severity: string; code: string; message: string; path?: string}[];
  nodeOptions: {id: string; selected: boolean; automatic: boolean; selectable: boolean; requirement: string}[];
  skills: (SectAtlasSkill & {
    available: boolean;
    requirement: string;
    skillLevel: number;
    changedFields: string[];
    changeSources: SectAtlasSkill['sources'];
  })[];
  panel: {attr: string; mode: 'add' | 'multiply'; value: number; sourceFact?: string}[];
  resources: SectAtlasSect['resources'];
};
export declare const SECT_ATLAS_SOURCE_HASH: string;
export declare function previewSectAtlasBuild(input: SectAtlasBuildInput): SectAtlasBuildPreview;
export declare function toggleSectAtlasNode(input: SectAtlasBuildInput, nodeId: string): SectAtlasBuildPreview;
`;

const files = [
  ['src/data/sects.json', `${JSON.stringify({ ...catalog, source }, null, 2)}\n`],
  ['src/lib/generated/sect-preview.js', runtimeOutput],
  ['src/lib/generated/sect-preview.d.ts', declarations],
] as const;
for (const [path, contents] of files) {
  const output = resolve(websiteRoot, path);
  await mkdir(dirname(output), { recursive: true });
  await writeFile(`${output}.tmp`, contents);
}
for (const [path] of files) {
  const output = resolve(websiteRoot, path);
  await rename(`${output}.tmp`, output);
}
console.log(`已导出 ${catalog.sects.length} 宗资料及同版本预览模块（${Math.ceil(runtime.length / 1024)} KiB），入口 ${atlasEntry}。`);
